-- Dedicated app schema. Existing schemas/tables/data are never dropped.
CREATE SCHEMA IF NOT EXISTS RURALLENS;
CREATE TABLE IF NOT EXISTS RURALLENS.DATASETS (
 DATASET_ID VARCHAR(40), METADATA VARCHAR(20000), CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS RURALLENS.BORROWERS (
 DATASET_ID VARCHAR(40), BORROWER_ID VARCHAR(80), BORROWER_NAME VARCHAR(200), BORROWER_TYPE VARCHAR(80),
 STATE VARCHAR(100), PRODUCT_TYPE VARCHAR(100), EXPOSURE DECIMAL(20,2), PAYLOAD VARCHAR(2000000),
 PRIMARY KEY (DATASET_ID, BORROWER_ID)
);
CREATE TABLE IF NOT EXISTS RURALLENS.MONTHLY_FEATURES (
 DATASET_ID VARCHAR(40), BORROWER_ID VARCHAR(80), MONTH_KEY VARCHAR(7),
 DPD30 DOUBLE, DPD60 DOUBLE, MISSED DOUBLE, PAYMENT_RATIO DOUBLE,
 CASHFLOW_GROWTH DOUBLE, CASHFLOW_VOLATILITY DOUBLE, INFLOW_CHANGE DOUBLE,
 OVER60_RATIO DOUBLE, RECEIVABLE_GROWTH DOUBLE, COLLECTION_DELAY DOUBLE,
 REVENUE_GROWTH DOUBLE, MARGIN_CHANGE DOUBLE, INVENTORY_GROWTH DOUBLE,
 BUYER_CONCENTRATION DOUBLE, LATE_BUYER_SHARE DOUBLE, TRANSACTION_SHIFT DOUBLE, TRANSACTION_VOLATILITY DOUBLE,
 PRIMARY KEY (DATASET_ID, BORROWER_ID, MONTH_KEY)
);
CREATE OR REPLACE VIEW RURALLENS.RISK_SCORES AS
WITH components AS (
 SELECT DATASET_ID,BORROWER_ID,MONTH_KEY,
 ROUND(LEAST(100,GREATEST(0,DPD30*9+DPD60*14+GREATEST(0,1-PAYMENT_RATIO)*70+MISSED*12)),1) AS REPAYMENT,
 ROUND(LEAST(100,GREATEST(0,GREATEST(0,-CASHFLOW_GROWTH)*130+CASHFLOW_VOLATILITY*35+GREATEST(0,-INFLOW_CHANGE)*75)),1) AS CASHFLOW,
 ROUND(LEAST(100,GREATEST(0,OVER60_RATIO*90+GREATEST(0,RECEIVABLE_GROWTH)*65+COLLECTION_DELAY*25)),1) AS RECEIVABLES,
 ROUND(LEAST(100,GREATEST(0,GREATEST(0,-REVENUE_GROWTH)*85+GREATEST(0,-MARGIN_CHANGE)*100+GREATEST(0,INVENTORY_GROWTH)*30)),1) AS BUSINESS,
 ROUND(LEAST(100,GREATEST(0,GREATEST(0,BUYER_CONCENTRATION-.35)*140+LATE_BUYER_SHARE*45)),1) AS CONCENTRATION,
 ROUND(LEAST(100,GREATEST(0,TRANSACTION_SHIFT*70+TRANSACTION_VOLATILITY*30)),1) AS TRANSACTION_ANOMALY
 FROM RURALLENS.MONTHLY_FEATURES
), weighted AS (
 SELECT components.*,ROUND(REPAYMENT*.25+CASHFLOW*.20+RECEIVABLES*.20+BUSINESS*.15+CONCENTRATION*.10+TRANSACTION_ANOMALY*.10,1) AS RISK_SCORE FROM components
)
SELECT weighted.*,CASE WHEN RISK_SCORE>=80 THEN 'CRITICAL' WHEN RISK_SCORE>=60 THEN 'HIGH' WHEN RISK_SCORE>=30 THEN 'MODERATE' ELSE 'LOW' END AS RISK_TIER FROM weighted;
CREATE OR REPLACE VIEW RURALLENS.CURRENT_RISK AS
SELECT * FROM RURALLENS.RISK_SCORES s WHERE MONTH_KEY=(SELECT MAX(f.MONTH_KEY) FROM RURALLENS.MONTHLY_FEATURES f WHERE f.DATASET_ID=s.DATASET_ID AND f.BORROWER_ID=s.BORROWER_ID);
